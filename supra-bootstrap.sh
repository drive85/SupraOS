  sed -i 's/GRUB_CMDLINE_LINUX_DEFAULT=\"\(.*\)\"/GRUB_CMDLINE_LINUX_DEFAULT=\"\1 quiet loglevel=0\"/' \"$GRUB\"
  echo 'Boot splash enabled (quiet)'
fi
