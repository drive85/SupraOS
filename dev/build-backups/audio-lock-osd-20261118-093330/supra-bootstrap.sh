  cat << 'BR' > /etc/local.d/brightness.start
#!/bin/sh
# SupraOS: restore last saved screen brightness (saved by the brightness keys)
b=\$(cat /home/$TARGET_USER/.cache/supra-brightness 2>/dev/null) || exit 0
max=\$(brightnessctl max) || exit 0
[ \"\$b\" -gt \"\$max\" ] && b=\$max
